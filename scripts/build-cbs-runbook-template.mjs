#!/usr/bin/env node
/**
 * Builds the Core Banking System Data Migration Runbook system template SQL (v1337 plan, slice 5).
 *
 *   node scripts/build-cbs-runbook-template.mjs <output.sql>      write the SQL
 *   node scripts/build-cbs-runbook-template.mjs --check           content check only
 *
 * Fails when the content names a vendor, product code, routine or person (rule 26), or a step has a
 * bad window. Content lives in scripts/cbs-runbook-template-content.mjs.
 */
/* global process, console */
import { writeFileSync } from 'node:fs'
import { RUNBOOK_STEPS, RUNBOOK_RECORD, stepFieldValues, contentProblems } from './cbs-runbook-template-content.mjs'

const TEMPLATE_ID = '00000000-0000-4000-b337-000000000001'
const problems = contentProblems()
if (problems.length) {
  console.error(problems.join('\n'))
  process.exit(1)
}
const counts = RUNBOOK_STEPS.reduce((t, s) => ({ ...t, [s.window]: (t[s.window] || 0) + 1 }), {})
console.log(`Content OK: ${RUNBOOK_STEPS.length} steps`, counts)
const out = process.argv[2]
if (!out || out === '--check') process.exit(0)

const children = RUNBOOK_STEPS.map((s, i) => ({
  title: s.title,
  description: null,
  status: 'not_started',
  field_values: stepFieldValues(s, i),
}))
const dollar = (v) => {
  const text = typeof v === 'string' ? v : JSON.stringify(v, null, 2)
  if (text.includes('$rb$')) throw new Error('content contains $rb$')
  return `$rb$${text}$rb$`
}

const sql = `-- ============================================================================
-- ${out.replace(/^.*[\\/]/, '').replace(/_.*$/, '')}: Core Banking System Data Migration Runbook — system template
-- ============================================================================
-- PRD: projectprd/v1337_cbs_data_migration_runbook_PRD.md (D5) · Plan: projectplan/v1337_cbs_data_migration_runbook_plan.md (slice 5)
--
-- One shipped (system) template for the Migration Runbook register (fin_migration_runbook) with
-- ${children.length} Runbook Steps children (fin_runbook_steps): preparation, static window, financial window in
-- batches (balance sheet, conventional products, Islamic products, internal / nostro, trade finance,
-- dynamic data), end of day, reconciliation and go / no-go. Generic and vendor-neutral; [placeholders]
-- for organisation-specific values. Each step's Runbook reference is the {{parent}} token, replaced
-- with the new runbook when a record is created from the template (v1375).
--
-- Generated by: node scripts/build-cbs-runbook-template.mjs <this file>  (content check runs first)
-- Re-runnable: template upserted (version + 1 when content changes), children replaced. Records
-- already created from the template are not touched. Display ID left blank (rule 16.2).
-- Run after: v1336, v1337, v1375, v1376.
-- ============================================================================

BEGIN;

INSERT INTO public.local_register_templates
  (id, display_id, register_key, template_scope, account_id, name, description, version,
   record_title, record_description, record_status, field_values)
VALUES (
  '${TEMPLATE_ID}'::uuid, '', 'fin_migration_runbook', 'system', NULL,
  ${dollar('Core Banking System Data Migration Runbook')},
  ${dollar(`Generic runbook for a core banking data migration run with ${children.length} ordered steps: loads with record counts and timings, suspense-category changes, backups, validations, checkpoints, end of day and the go / no-go decision. Fill the bracketed placeholders.`)},
  1,
  ${dollar(RUNBOOK_RECORD.title)},
  ${dollar(RUNBOOK_RECORD.description)},
  'planned',
  ${dollar(RUNBOOK_RECORD.field_values)}::jsonb
)
ON CONFLICT (id) DO UPDATE SET
  name               = EXCLUDED.name,
  description        = EXCLUDED.description,
  record_title       = EXCLUDED.record_title,
  record_description = EXCLUDED.record_description,
  record_status      = EXCLUDED.record_status,
  version            = public.local_register_templates.version
                       + CASE WHEN public.local_register_templates.field_values IS DISTINCT FROM EXCLUDED.field_values THEN 1 ELSE 0 END,
  field_values       = EXCLUDED.field_values,
  is_archived        = FALSE,
  updated_at         = NOW();

DELETE FROM public.local_register_template_children WHERE template_id = '${TEMPLATE_ID}'::uuid;

INSERT INTO public.local_register_template_children
  (template_id, link_field_key, register_key, sort_order, title, description, status, field_values)
SELECT '${TEMPLATE_ID}'::uuid, 'runbook', 'fin_runbook_steps', c.ord::int,
       c.e ->> 'title', c.e ->> 'description', c.e ->> 'status', c.e -> 'field_values'
FROM jsonb_array_elements(${dollar(children)}::jsonb) WITH ORDINALITY AS c(e, ord);

COMMIT;

-- Check: one template and ${children.length} steps, by window.
SELECT t.display_id, t.name, t.version,
       (SELECT count(*) FROM public.local_register_template_children c WHERE c.template_id = t.id) AS steps,
       (SELECT string_agg(w || ': ' || n, ', ') FROM (
          SELECT c.field_values ->> 'window' AS w, count(*) AS n, min(c.sort_order) AS first
          FROM public.local_register_template_children c WHERE c.template_id = t.id GROUP BY 1 ORDER BY first) x) AS by_window
FROM public.local_register_templates t
WHERE t.id = '${TEMPLATE_ID}'::uuid;
`
writeFileSync(out, sql)
console.log('written', out)
