/**
 * Generates SQL/v1542_plan_list_tables.sql from PLAN_LISTS (packages/shared/src/services/planListTablesService.js),
 * so the table columns and the JSON copy aliases always match what the app reads and writes.
 *   node scripts/generate-plan-list-tables-sql.mjs <out.sql>
 */
import fs from 'node:fs'
import { PLAN_LISTS } from '../packages/shared/src/services/planListTablesService.js'

const out = process.argv[2]
const PARENT = { project: 'project_plans', stage: 'stage_plans' }
const lines = []
const p = (s = '') => lines.push(s)

p('-- ============================================================================')
p('-- v1542 — Plan list tables (owner decision 2026-11-21: plan lists are kept as rows in tables, not JSON)')
p('-- ============================================================================')
p('-- Key risks, quality gates and budget breakdown (project + stage plans), stage dependencies and stage')
p('-- resource allocation move from JSONB columns on project_plans / stage_plans to their own tables.')
p('-- The forms edit them as tables (PlanListTable); the plan services write these tables.')
p('-- Generated by scripts/generate-plan-list-tables-sql.mjs from PLAN_LISTS — edit that config, not this file.')
p('--')
p('-- Access mirrors the parent plan (SQL v206): read when the plan is visible to you; change only when you could')
p('-- edit the plan (PMO / System Admin unless baselined; otherwise author, owner or creator with owner/admin')
p('-- project access while the plan is draft or under review). SECURITY DEFINER helpers with row_security off')
p('-- avoid the RLS-join HTTP 500 class of bug.')
p('--')
p('-- Existing JSON values are copied once (arrays of objects, arrays of text, { key: value } maps). The old JSON')
p('-- columns are left in place and no longer written; drop them later once the copy is confirmed.')
p('-- Idempotent. Prerequisites: v205 / v206 (plan tables). After running: re-run SQL/v1251_planner_table_wall.sql.')
p('-- ============================================================================')
p()
p('-- Helpers: read a value from a legacy JSON element.')
p(`CREATE OR REPLACE FUNCTION public.plan_list_pick(p_val JSONB, p_keys TEXT[])
RETURNS TEXT LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN jsonb_typeof(p_val) = 'object' THEN (
    SELECT NULLIF(btrim(p_val ->> k), '') FROM unnest(p_keys) WITH ORDINALITY AS u(k, n)
    WHERE NULLIF(btrim(p_val ->> k), '') IS NOT NULL ORDER BY n LIMIT 1) END
$$;`)
p(`CREATE OR REPLACE FUNCTION public.plan_list_scalar(p_val JSONB)
RETURNS TEXT LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN jsonb_typeof(p_val) IN ('string', 'number', 'boolean') THEN NULLIF(btrim(p_val #>> '{}'), '') END
$$;`)
p(`CREATE OR REPLACE FUNCTION public.plan_list_numeric(p_text TEXT)
RETURNS NUMERIC LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN regexp_replace(coalesce(p_text, ''), '[,\\s]', '', 'g') ~ '^-?[0-9]+(\\.[0-9]+)?$'
    THEN regexp_replace(p_text, '[,\\s]', '', 'g')::NUMERIC END
$$;`)
p()
for (const [kind, parent] of Object.entries(PARENT)) {
  p(`-- Who may read / change the lists of a ${kind} plan.`)
  p(`CREATE OR REPLACE FUNCTION public.auth_user_can_view_${kind}_plan(p_plan_id UUID)
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public SET row_security = off AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.${parent} pl
    WHERE pl.id = p_plan_id AND pl.is_deleted = FALSE
      AND (
        EXISTS (SELECT 1 FROM public.user_projects up JOIN public.users u ON up.user_id = u.id
                WHERE u.auth_user_id = auth.uid() AND up.project_id = pl.project_id AND up.is_deleted = FALSE)
        OR EXISTS (SELECT 1 FROM public.user_roles ur JOIN public.roles r ON ur.role_id = r.id JOIN public.users u ON ur.user_id = u.id
                   WHERE u.auth_user_id = auth.uid() AND r.role_name IN ('pmo_admin', 'System Admin')
                     AND ur.is_active = TRUE AND ur.is_deleted = FALSE)
      )
  )
$$;`)
  p(`CREATE OR REPLACE FUNCTION public.auth_user_can_edit_${kind}_plan(p_plan_id UUID)
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public SET row_security = off AS $$
  WITH me AS (SELECT id FROM public.users WHERE auth_user_id = auth.uid() AND is_deleted = FALSE LIMIT 1)
  SELECT EXISTS (
    SELECT 1 FROM public.${parent} pl
    WHERE pl.id = p_plan_id AND pl.is_deleted = FALSE AND pl.is_baseline = FALSE
      AND (
        EXISTS (SELECT 1 FROM public.user_roles ur JOIN public.roles r ON ur.role_id = r.id JOIN public.users u ON ur.user_id = u.id
                WHERE u.auth_user_id = auth.uid() AND r.role_name IN ('pmo_admin', 'System Admin')
                  AND ur.is_active = TRUE AND ur.is_deleted = FALSE)
        OR (
          pl.status IN ('draft', 'under_review')
          AND (pl.author_id = (SELECT id FROM me) OR pl.owner_id = (SELECT id FROM me) OR pl.created_by = (SELECT id FROM me))
          AND EXISTS (SELECT 1 FROM public.user_projects up JOIN public.users u ON up.user_id = u.id
                      WHERE u.auth_user_id = auth.uid() AND up.project_id = pl.project_id
                        AND up.access_level IN ('owner', 'admin') AND up.is_deleted = FALSE)
        )
      )
  )
$$;`)
  p(`GRANT EXECUTE ON FUNCTION public.auth_user_can_view_${kind}_plan(UUID), public.auth_user_can_edit_${kind}_plan(UUID) TO authenticated;`)
  p()
}

const registry = []
for (const [kind, cfg] of Object.entries(PLAN_LISTS)) {
  const parent = PARENT[kind]
  const fk = cfg.parentColumn
  for (const [listKey, list] of Object.entries(cfg.lists)) {
    const t = `public.${list.table}`
    const colDefs = list.columns.map((c) => `  ${c.key} ${c.numeric ? 'NUMERIC(18,2)' : c.type === 'date' ? 'TEXT' : 'TEXT'}`)
    p(`-- ${list.table}: ${kind} plan ${listKey.replace(/_/g, ' ')} (${list.columns.map((c) => c.label).join(' | ')}).`)
    p(`CREATE TABLE IF NOT EXISTS ${t} (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  ${fk} UUID NOT NULL REFERENCES public.${parent}(id) ON DELETE CASCADE,
  sort_order INTEGER NOT NULL DEFAULT 0,
${colDefs.join(',\n')},
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);`)
    p(`CREATE INDEX IF NOT EXISTS idx_${list.table}_parent ON ${t} (${fk}, sort_order);`)
    p(`ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`)
    p(`GRANT SELECT, INSERT, UPDATE, DELETE ON ${t} TO authenticated;`)
    for (const [op, using, check] of [
      ['select', `public.auth_user_can_view_${kind}_plan(${fk})`, null],
      ['insert', null, `public.auth_user_can_edit_${kind}_plan(${fk})`],
      ['update', `public.auth_user_can_edit_${kind}_plan(${fk})`, `public.auth_user_can_edit_${kind}_plan(${fk})`],
      ['delete', `public.auth_user_can_edit_${kind}_plan(${fk})`, null],
    ]) {
      const name = `${list.table}_${op}`
      p(`DROP POLICY IF EXISTS ${name} ON ${t};`)
      p(`CREATE POLICY ${name} ON ${t} FOR ${op.toUpperCase()} TO authenticated${using ? ` USING (${using})` : ''}${check ? ` WITH CHECK (${check})` : ''};`)
    }
    // One-time copy of the legacy JSON column (only plans with no rows yet).
    const keyCol = list.mapKeyColumn || list.columns[0].key
    const valueCol = list.mapValueColumn || list.columns[1].key
    const firstCol = list.columns[0].key
    const exprs = list.columns.map((c) => {
      const keys = `ARRAY[${[c.key, ...(c.aliases || [])].map((k) => `'${k}'`).join(', ')}]`
      let e = `public.plan_list_pick(e.val, ${keys})`
      if (c.key === keyCol) e = `COALESCE(e.map_key, ${e}${c.key === firstCol ? ', CASE WHEN e.map_key IS NULL THEN public.plan_list_scalar(e.val) END' : ''})`
      else if (c.key === firstCol) e = `COALESCE(${e}, CASE WHEN e.map_key IS NULL THEN public.plan_list_scalar(e.val) END)`
      if (c.key === valueCol && c.key !== keyCol) e = `COALESCE(${e}, CASE WHEN e.map_key IS NOT NULL THEN public.plan_list_scalar(e.val) END)`
      return c.numeric ? `public.plan_list_numeric(${e})` : e
    })
    p(`INSERT INTO ${t} (${fk}, sort_order, ${list.columns.map((c) => c.key).join(', ')})
SELECT e.plan_id, e.ord, ${exprs.join(',\n       ')}
FROM (
  SELECT pl.id AS plan_id, a.ord::INTEGER AS ord, NULL::TEXT AS map_key, a.val
  FROM public.${parent} pl CROSS JOIN LATERAL jsonb_array_elements(pl.${listKey}) WITH ORDINALITY AS a(val, ord)
  WHERE jsonb_typeof(pl.${listKey}) = 'array'
  UNION ALL
  SELECT pl.id, o.ord::INTEGER, o.k, o.val
  FROM public.${parent} pl CROSS JOIN LATERAL jsonb_each(pl.${listKey}) WITH ORDINALITY AS o(k, val, ord)
  WHERE jsonb_typeof(pl.${listKey}) = 'object'
) e
WHERE e.val IS NOT NULL AND e.val NOT IN ('{}'::jsonb, 'null'::jsonb, '""'::jsonb)
  AND NOT EXISTS (SELECT 1 FROM ${t} x WHERE x.${fk} = e.plan_id);`)
    p(`COMMENT ON COLUMN public.${parent}.${listKey} IS 'Superseded by ${t} (v1542). Kept for reference; no longer written by the app.';`)
    p()
    registry.push(`  ('${list.table}', '${kind === 'project' ? 'Project' : 'Stage'} plan ${listKey.replace(/_/g, ' ')}: one row per item (${list.columns.map((c) => c.label).join(', ')})', false, true)`)
  }
}
p('-- Register new tables in database_tables registry')
p(`INSERT INTO database_tables (table_name, table_description, is_system_table, is_active)
VALUES
${registry.join(',\n')}
ON CONFLICT (table_name) DO UPDATE SET
  table_description = EXCLUDED.table_description,
  is_system_table = EXCLUDED.is_system_table,
  updated_at = NOW();`)
p()
p('-- Check: rows copied per table')
p(Object.values(PLAN_LISTS).flatMap((cfg) => Object.values(cfg.lists).map((l) => `SELECT '${l.table}' AS table_name, count(*) AS rows FROM public.${l.table}`)).join('\nUNION ALL ') + ';')
fs.writeFileSync(out, lines.join('\n') + '\n')
console.log('Wrote', out)
