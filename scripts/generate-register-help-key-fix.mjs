/**
 * Generates SQL that copies register help seeded under a menu CATEGORY code (register:<category>:<field>)
 * to each real register in that category that has the field (register:<register_key>:<field>).
 * v1345 fix 2026-11-22 — see scripts/field-help-content/register-keys.mjs for the cause.
 *   node scripts/generate-register-help-key-fix.mjs <out.sql>
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadRegisterKeys, expandRegisterKey } from './field-help-content/register-keys.mjs'
import { extractSeededKeys } from './check-field-help.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = process.argv[2]
const maps = loadRegisterKeys()
const sqlDir = path.join(ROOT, 'SQL')
const help = new Set(fs.readdirSync(sqlDir).filter((f) => f.endsWith('.sql')).flatMap((f) => [...extractSeededKeys(fs.readFileSync(path.join(sqlDir, f), 'utf8')).help]))
const pairs = []
for (const k of help) {
  const m = /^register:([^:]+):(.+)$/.exec(k)
  if (!m || m[1] === '*' || maps.registerKeys.has(m[1])) continue
  for (const real of expandRegisterKey(k, maps)) if (real !== k) pairs.push([k, real])
}
pairs.sort((a, b) => (a[1] < b[1] ? -1 : 1))
const lines = []
lines.push('-- ============================================================================')
lines.push(`-- ${path.basename(out, '.sql').split('_')[0]} — Register field help under the real register keys (v1345 fix, 2026-11-22)`)
lines.push('-- ============================================================================')
lines.push('-- Cause: v1345 slice 2 keyed the industry registers\' help by the sidebar menu CATEGORY code')
lines.push('-- (register:ict_cat_technical_debt:…, register:con_cat_commercial:…), which no register uses. The form asks for')
lines.push('-- register:<register_key>:<field_key>, so fields unique to those registers showed no help (fields with a common')
lines.push('-- register:*:<field> entry still did).')
lines.push(`-- Fix: copy each category-keyed row to every register in that category that has the field (${pairs.length} rows).`)
lines.push('-- The category-keyed rows are left in place (harmless; nothing asks for them).')
lines.push('-- Generated by scripts/generate-register-help-key-fix.mjs. Idempotent; refreshes the text if re-run.')
lines.push('-- Prerequisites: v1490 and the slice 2 register seeds (v1497–v1514).')
lines.push('-- ============================================================================')
lines.push('')
lines.push('INSERT INTO public.field_help (help_key, form_key, locale, title, purpose, examples, format_notes, extra_notes, learn_more_kind, learn_more_key, module_code, is_active)')
lines.push('SELECT m.real_key, h.form_key, h.locale, h.title, h.purpose, h.examples, h.format_notes, h.extra_notes, h.learn_more_kind, h.learn_more_key, h.module_code, h.is_active')
lines.push('FROM (VALUES')
lines.push(pairs.map(([from, to]) => `  ('${from}', '${to}')`).join(',\n'))
lines.push(') AS m(category_key, real_key)')
lines.push('JOIN public.field_help h ON h.help_key = m.category_key')
lines.push('ON CONFLICT (help_key, form_key, locale) DO UPDATE SET')
lines.push('  title = EXCLUDED.title, purpose = EXCLUDED.purpose, examples = EXCLUDED.examples, format_notes = EXCLUDED.format_notes,')
lines.push('  extra_notes = EXCLUDED.extra_notes, learn_more_kind = EXCLUDED.learn_more_kind, learn_more_key = EXCLUDED.learn_more_key,')
lines.push('  module_code = EXCLUDED.module_code, is_active = TRUE;')
lines.push('')
lines.push('-- Check: rows now under real register keys that were copied from category keys')
lines.push(`SELECT count(*) AS real_key_rows FROM public.field_help WHERE help_key IN (${pairs.slice(0, 3).map(([, t]) => `'${t}'`).join(', ')}, '…');`.replace(", '…'", ''))
fs.writeFileSync(out, lines.join('\n') + '\n')
console.log('Wrote', out, pairs.length, 'rows')
