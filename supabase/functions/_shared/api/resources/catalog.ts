import type { ResourceDef } from '../openapi.ts'

export type TableResource = ResourceDef & {
  table: string
  idColumn: string
  displayIdColumn?: string
  accountColumn?: string
  projectColumn?: string
  softDelete?: boolean
  select: string
  mapRow: (row: Record<string, unknown>) => Record<string, unknown>
}

function money(v: unknown): string | null {
  if (v === null || v === undefined || v === '') return null
  const n = Number(v)
  return Number.isFinite(n) ? n.toFixed(2) : String(v)
}

function iso(v: unknown): string | null {
  if (!v) return null
  const d = new Date(String(v))
  return Number.isNaN(d.getTime()) ? null : d.toISOString()
}

function baseMap(row: Record<string, unknown>, displayKey?: string): Record<string, unknown> {
  const id = displayKey && row[displayKey] ? row[displayKey] : row.id
  return {
    id,
    uuid: row.id,
    created_at: iso(row.created_at),
    updated_at: iso(row.updated_at),
  }
}

