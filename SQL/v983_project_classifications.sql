-- ============================================================================
-- v983: Project Classifications / Complexity Levels (Phase 2 of v982 SaaS User
-- Journey — PMO Configuration Zone)
-- ============================================================================
-- projectplan/v982_phase2_pmo_configuration_zone_plan.md, task A.
--
-- New organisation-scoped reference table so a PMO Admin can define classification/complexity
-- levels once and apply them to projects. Per the plan's decision 3 (accepted by default per
-- user authorization): classifications are descriptive AND governance-linking — a project's
-- classification_id, together with its industry template, determines which
-- pmo_industry_template_governance profile it inherits (see v984).
--
-- SCOPE DECISION (public-only, no separate sim.project_classifications table): PMO/organisation
-- configuration in this codebase already lives exclusively in `public` regardless of which app
-- edits it — confirmed by v982 Phase 1 (organisationService.js/invitationService.js resolve to
-- platformDb/public from BOTH apps) and v914 (org_menu_bundles, public-only, edited from both
-- Platform's admin/manage-menu-bundles and Simulator's simulator/pmo/manage-menu-bundles routes).
-- "Organisation" is one shared public.accounts concept across Platform and Simulator; only
-- simulation-run-scoped data (sim.practice_projects, sim.simulation_runs, ...) lives in `sim`.
-- This table follows that same established pattern. `sim.practice_projects` (a project-shaped
-- entity that legitimately wants a classification) gets a classification_id column referencing
-- this public table instead of a duplicate sim table (see section 3).
--
-- No Admin ID Generation wiring (rule 16.2): classification_code is a short, PMO-admin-typed
-- free-text code (e.g. "STD", "COMPLEX"), the same shape as project_types.type_code, which also
-- has no Admin ID Generation rule — not a human-readable reference generated by the system.
--
-- Prerequisites: public.accounts, public.users, public.projects, sim.practice_projects,
-- public.is_pmo_admin_user(), public.get_user_accounts(uuid) (v87_unified_auth_functions.sql).
-- ============================================================================

-- ── 1. public.project_classifications ──────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.project_classifications (
  id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  account_id            UUID NOT NULL REFERENCES public.accounts(id) ON DELETE CASCADE,
  classification_code   VARCHAR(50) NOT NULL,
  classification_name   VARCHAR(150) NOT NULL,
  complexity_level      VARCHAR(20) NOT NULL DEFAULT 'medium'
                          CHECK (complexity_level IN ('low', 'medium', 'high', 'very_high')),
  description           TEXT,
  color                 VARCHAR(20),
  is_active             BOOLEAN NOT NULL DEFAULT TRUE,
  is_deleted            BOOLEAN NOT NULL DEFAULT FALSE,
  created_by            UUID REFERENCES public.users(id),
  updated_by            UUID REFERENCES public.users(id),
  created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_project_classifications_code_per_account UNIQUE (account_id, classification_code)
);

COMMENT ON TABLE public.project_classifications IS
  'v983/v982 Phase 2: organisation-defined project classification/complexity levels. Descriptive '
  'and governance-linking (see pmo_industry_template_governance.classification_id, v984).';

CREATE INDEX IF NOT EXISTS idx_project_classifications_account
  ON public.project_classifications(account_id) WHERE is_deleted = FALSE;

-- ── 2. public.projects.classification_id ────────────────────────────────────────

ALTER TABLE public.projects
  ADD COLUMN IF NOT EXISTS classification_id UUID REFERENCES public.project_classifications(id) ON DELETE SET NULL;

COMMENT ON COLUMN public.projects.classification_id IS
  'v983: optional link to the organisation''s project_classifications. Drives which '
  'pmo_industry_template_governance profile (v984) a project inherits when created from a '
  'classified industry template.';

CREATE INDEX IF NOT EXISTS idx_projects_classification_id
  ON public.projects(classification_id) WHERE is_deleted = FALSE;

-- ── 3. sim.practice_projects.classification_id (schema-level parity, rule 34.1) ────
-- Practice projects can reference the same public.project_classifications rows (organisation
-- config is shared across apps, see header). The auto-provisioning JS wiring (v984/service) is
-- Platform-only this phase — sim.stage_gate_reviews is keyed by run_id, not project_id, a
-- materially different data model (documented gap, same class of divergence as v893's Simulator
-- Practice-module carve-out). The column itself is added now so the schema is ready whenever that
-- Simulator-specific auto-provisioning mechanism is designed.

ALTER TABLE sim.practice_projects
  ADD COLUMN IF NOT EXISTS classification_id UUID REFERENCES public.project_classifications(id) ON DELETE SET NULL;

COMMENT ON COLUMN sim.practice_projects.classification_id IS
  'v983: optional link to the organisation''s public.project_classifications (shared org config, '
  'see v983 header). Auto-provisioning of governed stage gates is not wired for practice '
  'projects this phase — documented gap, sim.stage_gate_reviews is run_id-scoped.';

-- ── 4. RLS ────────────────────────────────────────────────────────────────────────
-- account_id-scoped via get_user_accounts(auth.uid()) (v87) — every member of the owning
-- organisation can read; only a PMO Admin who is also a member of that same account can write.
-- This is intentionally stricter than the org_menu_bundles (v914) precedent (broad authenticated
-- SELECT, no account_id check) and the expense_approval_thresholds (v420) "maintain" policy
-- (is_pmo_admin_user() with no account match) — both would fail this phase's mandatory
-- cross-tenant isolation test. New tables in this phase use the stricter, account_id-matched
-- shape throughout.

ALTER TABLE public.project_classifications ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.project_classifications TO authenticated;

DROP POLICY IF EXISTS policy_project_classifications_select ON public.project_classifications;
CREATE POLICY policy_project_classifications_select ON public.project_classifications
  FOR SELECT TO authenticated
  USING (
    is_deleted = FALSE
    AND account_id IN (SELECT ga.account_id FROM public.get_user_accounts(auth.uid()) ga)
  );

DROP POLICY IF EXISTS policy_project_classifications_write ON public.project_classifications;
CREATE POLICY policy_project_classifications_write ON public.project_classifications
  FOR ALL TO authenticated
  USING (
    public.is_pmo_admin_user()
    AND account_id IN (SELECT ga.account_id FROM public.get_user_accounts(auth.uid()) ga)
  )
  WITH CHECK (
    public.is_pmo_admin_user()
    AND account_id IN (SELECT ga.account_id FROM public.get_user_accounts(auth.uid()) ga)
  );

-- ── 5. database_tables registry (mandatory) ─────────────────────────────────────

INSERT INTO public.database_tables (table_name, table_description, is_system_table, is_active)
VALUES
  ('project_classifications', 'Organisation-defined project classification/complexity levels (PMO Configuration Zone, v982 Phase 2)', false, true)
ON CONFLICT (table_name) DO UPDATE SET
  table_description = EXCLUDED.table_description,
  is_system_table = EXCLUDED.is_system_table,
  updated_at = NOW();

-- ── 6. Seed: default classification set per existing account (rule 18.2) ───────
-- Idempotent — only seeds an account that currently has ZERO classification rows (so an org that
-- has already defined its own set, or was already seeded, is left untouched on re-run). Four
-- generic, industry-neutral complexity tiers — standard PM vocabulary, not an invented content
-- list (flagged in the implementation report per the task's own review instruction, out of an
-- abundance of caution, even though this is a short/standard set rather than a large one).

DO $$
DECLARE
  v_account RECORD;
BEGIN
  FOR v_account IN SELECT id FROM public.accounts WHERE is_deleted = FALSE LOOP
    IF NOT EXISTS (SELECT 1 FROM public.project_classifications WHERE account_id = v_account.id) THEN
      INSERT INTO public.project_classifications
        (account_id, classification_code, classification_name, complexity_level, description, color, is_active)
      VALUES
        (v_account.id, 'LOW', 'Low Complexity', 'low', 'Small, well-understood projects with minimal governance overhead.', '#22C55E', TRUE),
        (v_account.id, 'STANDARD', 'Standard Complexity', 'medium', 'Typical projects following the organisation''s default methodology and governance.', '#3B82F6', TRUE),
        (v_account.id, 'COMPLEX', 'High Complexity', 'high', 'Larger or higher-risk projects requiring additional stage gates and approvals.', '#F59E0B', TRUE),
        (v_account.id, 'STRATEGIC', 'Strategic / Enterprise', 'very_high', 'Organisation-critical projects requiring the fullest governance profile available.', '#EF4444', TRUE)
      ON CONFLICT (account_id, classification_code) DO NOTHING;
    END IF;
  END LOOP;
END $$;

DO $$ BEGIN RAISE NOTICE 'v983_project_classifications.sql applied successfully'; END $$;
