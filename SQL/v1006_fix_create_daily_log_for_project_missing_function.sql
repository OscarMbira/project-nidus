-- v1006_fix_create_daily_log_for_project_missing_function.sql
--
-- Root cause: v756b migrated daily_logs.log_reference onto the Admin ID Generation trigger
-- (trg_daily_logs_admin_display_id) and dropped the old public.generate_log_reference()
-- function it replaced — but create_daily_log_for_project() (redefined as recently as v705)
-- still calls generate_log_reference() directly to build the value it inserts. Since that
-- function no longer exists, every call fails with "function generate_log_reference() does
-- not exist" — and trg_projects_after_insert_daily_log calls this function automatically
-- after every project INSERT, so this broke project creation entirely, not just Daily Log.
--
-- (Same underlying migration gap already worked around in SQL/v977_projects_daily_log_seed_data.sql
-- for hand-written seed rows — this fixes the live function so the workaround isn't needed
-- for real, application-driven inserts going forward.)
--
-- Fix: stop generating the reference in PL/pgSQL — insert log_reference as '' (blank) and let
-- the Admin ID Generation AFTER INSERT trigger assign it, exactly like every other display-ID
-- column in this codebase (rule 16.2).

CREATE OR REPLACE FUNCTION create_daily_log_for_project(p_project_id UUID, p_user_id UUID)
RETURNS UUID AS $$
DECLARE
    v_log_id       UUID;
    v_programme_id UUID;
BEGIN
    -- Return existing log if one already exists for this project
    SELECT id INTO v_log_id
    FROM daily_logs
    WHERE project_id = p_project_id
      AND is_deleted = FALSE;

    IF v_log_id IS NOT NULL THEN
        RETURN v_log_id;
    END IF;

    -- Resolve programme_id via the programme_projects linking table.
    -- projects.programme_id does not exist; the association is stored in
    -- programme_projects (created in v37_programme_management.sql).
    SELECT pp.programme_id INTO v_programme_id
    FROM programme_projects pp
    WHERE pp.project_id = p_project_id
    LIMIT 1;

    -- Create the daily log — log_reference left blank; trg_daily_logs_admin_display_id
    -- (v756b) assigns the real reference in an AFTER INSERT trigger.
    INSERT INTO daily_logs (
        project_id,
        programme_id,
        log_reference,
        created_by,
        visibility,
        is_active
    )
    VALUES (
        p_project_id,
        v_programme_id,   -- NULL when project has no programme assignment
        '',
        p_user_id,
        'team',
        TRUE
    )
    RETURNING id INTO v_log_id;

    RETURN v_log_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

COMMENT ON FUNCTION create_daily_log_for_project(UUID, UUID) IS
  'v1006 fix: log_reference is generated by the Admin ID Generation trigger '
  '(trg_daily_logs_admin_display_id, v756b) — generate_log_reference() no longer exists '
  'and must never be called here again. programme_id resolved via programme_projects '
  '(v705 fix, projects.programme_id does not exist).';

DO $$
BEGIN
  RAISE NOTICE 'v1006: create_daily_log_for_project() no longer calls the missing generate_log_reference() — project creation''s automatic daily log will succeed again.';
END $$;
