       CASE WHEN i.has_project_id THEN
         (xpath('/row/n/text()', query_to_xml(format('SELECT count(*) AS n FROM public.%I WHERE project_id = %L', i.table_name, (SELECT id FROM seed)), false, true, '')))[1]::text::int
       END AS seed_rows,
       (xpath('/row/n/text()', query_to_xml(format('SELECT count(*) AS n FROM public.%I', i.table_name), false, true, '')))[1]::text::int AS total_rows
