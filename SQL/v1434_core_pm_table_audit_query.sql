info AS (
  SELECT w.table_name, t.table_type,
         (SELECT count(*) FROM information_schema.columns c WHERE c.table_schema = 'public' AND c.table_name = w.table_name) AS columns,
         EXISTS (SELECT 1 FROM information_schema.columns c WHERE c.table_schema = 'public' AND c.table_name = w.table_name AND c.column_name = 'project_id') AS has_project_id
  FROM wanted w
  JOIN information_schema.tables t ON t.table_schema = 'public' AND t.table_name = w.table_name
)
